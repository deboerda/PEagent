"""Idempotent project-side PE script preparation.

This module edits only the project script files.  Native PE loading and
execution remain explicit operations in ``native_flow`` so a project-startup
include is never loaded a second time by accident.
"""

from __future__ import annotations

import os
import re
import shutil
import time
from pathlib import Path


_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_INCLUDE_LINE = re.compile(
    r"(?im)^(?P<indent>[ \t]*)include\s*\{\s*"
    r"(?P<path>[^}\r\n]+?)\s*\}\s*;\s*(?P<eol>\r\n|\n|$)"
)


def _decode(data: bytes, default: str = "gb18030") -> tuple[str, str]:
    if data.startswith(b"\xef\xbb\xbf"):
        return data.decode("utf-8-sig"), "utf-8-sig"
    if data.startswith(b"\xff\xfe") or data.startswith(b"\xfe\xff"):
        for encoding in ("utf-16", "utf-16-le", "utf-16-be"):
            try:
                return data.decode(encoding), encoding
            except UnicodeDecodeError:
                pass
    for encoding in ("utf-8", "gb18030", "cp936"):
        try:
            return data.decode(encoding), encoding
        except UnicodeDecodeError:
            pass
    return data.decode(default, errors="replace"), default


def _read(path: Path, default: str = "gb18030") -> tuple[str, str]:
    return _decode(path.read_bytes(), default)


def _newline(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def _write(path: Path, text: str, encoding: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temp.write_bytes(text.encode(encoding))
    os.replace(temp, path)


def _backup(path: Path) -> str:
    stamp = time.strftime("%Y%m%d%H%M%S")
    candidate = path.with_name(f"{path.name}.bak.{stamp}")
    suffix = 1
    while candidate.exists():
        candidate = path.with_name(f"{path.name}.bak.{stamp}.{suffix}")
        suffix += 1
    shutil.copy2(path, candidate)
    return str(candidate)


def _normal_path(value: str) -> str:
    return value.strip().strip('"').replace("\\", "/").lstrip("./").casefold()


def _inside(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def _include_entries(text: str, include_path: str):
    target = _normal_path(include_path)
    return [m for m in _INCLUDE_LINE.finditer(text) if _normal_path(m.group("path")) == target]


def _ensure_include(text: str, include_path: str) -> tuple[str, str, int]:
    matches = _include_entries(text, include_path)
    if len(matches) > 1:
        # Keep the first exact match and remove only duplicate include lines.
        for match in reversed(matches[1:]):
            text = text[:match.start()] + text[match.end():]
        return text, "deduplicated", len(matches)
    if len(matches) == 1:
        return text, "already_present", 1

    nl = _newline(text) if text else "\r\n"
    line = f"    include{{{include_path}}};{nl}"
    if not text.strip():
        return f"Script{{{nl}{line}}}{nl}", "created", 0
    if not re.search(r"(?i)\bScript\s*\{", text):
        raise ValueError("include file does not contain a Script block")
    closing = text.rfind("}")
    if closing < 0:
        raise ValueError("include file has no closing Script brace")
    prefix = text[:closing]
    if prefix and not prefix.endswith(("\r\n", "\n")):
        prefix += nl
    return prefix + line + text[closing:], "added", 0


def _escape_message(message: str) -> str:
    return message.replace("\\", "\\\\").replace('"', '\\"').replace("\r", "\\r").replace("\n", "\\n")


def render_script(function_name: str, message: str = "", body: str = "", newline: str = "\r\n") -> str:
    if not _IDENTIFIER.fullmatch(function_name):
        raise ValueError(f"invalid function name: {function_name}")
    if body.strip() and re.search(r"(?i)\bScript\s*\{", body):
        raise ValueError("body must contain function statements, not a complete Script block")
    statements = body.strip()
    if not statements:
        marker = message or function_name
        statements = f'outputMessage("{_escape_message(marker)}");'
    statement_lines = statements.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    indented = newline.join(f"    {line}" if line else "" for line in statement_lines)
    return (
        f"// Generated by peagent-cli. Edit the function body as needed.{newline}"
        f"Script{{{newline}"
        f"void {function_name}(){{{newline}"
        f"{indented}{newline}"
        f"}}{newline}"
        f"}}{newline}"
    )


def prepare_project_script(
    *,
    project: str,
    function_name: str,
    script_name: str = "",
    message: str = "",
    body: str = "",
    include_file: str = "",
    script_file: str = "",
    overwrite: bool = False,
    dry_run: bool = False,
) -> dict:
    """Create a function script and ensure one matching include entry.

    Existing identical files are left untouched.  Existing conflicting script
    files are rejected unless ``overwrite`` is true.  Duplicate exact include
    entries are reduced to one entry, with a backup created before mutation.
    """
    project_path = Path(project).expanduser().resolve()
    project_dir = project_path if project_path.is_dir() else project_path.parent
    if not project_dir.exists():
        return {"success": False, "error": f"project directory does not exist: {project_dir}"}

    if not _IDENTIFIER.fullmatch(function_name):
        return {"success": False, "error": f"invalid function name: {function_name}"}

    script_dir = project_dir / "main" / "Script"
    default_script_name = script_name or function_name
    if not default_script_name.casefold().endswith(".script"):
        default_script_name += ".script"
    script_path = Path(script_file).expanduser().resolve() if script_file else script_dir / default_script_name
    include_path = Path(include_file).expanduser().resolve() if include_file else script_dir / "include.script"
    if script_path.suffix.casefold() != ".script":
        script_path = script_path.with_suffix(".script")
    if not _inside(script_path, project_dir) or not _inside(include_path, project_dir):
        return {"success": False, "error": "script and include files must be under the project directory"}

    try:
        include_relative = os.path.relpath(script_path, include_path.parent).replace(os.sep, "/")
    except ValueError as exc:
        return {"success": False, "error": f"cannot create project-relative include path: {exc}"}

    include_exists = include_path.is_file()
    include_text, include_encoding = _read(include_path) if include_exists else ("", "gb18030")
    script_encoding = include_encoding
    nl = _newline(include_text) if include_text else "\r\n"
    rendered = render_script(function_name, message=message, body=body, newline=nl)

    script_exists = script_path.is_file()
    script_status = "created"
    if script_exists:
        existing_script, script_encoding = _read(script_path, include_encoding)
        if existing_script == rendered:
            script_status = "already_present"
        elif not overwrite:
            return {
                "success": False,
                "error": "script file exists with different content; pass overwrite=true to replace it",
                "script_file": str(script_path),
                "include_file": str(include_path),
                "script_status": "conflict",
            }
        else:
            script_status = "replaced"

    try:
        new_include, include_status, previous_count = _ensure_include(include_text, include_relative)
    except ValueError as exc:
        return {
            "success": False,
            "error": str(exc),
            "script_file": str(script_path),
            "include_file": str(include_path),
        }

    result = {
        "success": True,
        "dry_run": dry_run,
        "project_dir": str(project_dir),
        "script_file": str(script_path),
        "include_file": str(include_path),
        "include_entry": include_relative,
        "script_status": script_status,
        "include_status": include_status,
        "previous_include_count": previous_count,
        "encoding": include_encoding,
        "script_encoding": script_encoding,
        "include_encoding": include_encoding,
        "backups": [],
    }
    if dry_run:
        return result

    created_script = False
    try:
        if script_status in {"created", "replaced"}:
            if script_exists:
                result["backups"].append(_backup(script_path))
            _write(script_path, rendered, script_encoding)
            created_script = script_status == "created"
        if new_include != include_text:
            if include_exists:
                result["backups"].append(_backup(include_path))
            _write(include_path, new_include, include_encoding)

        verified_script, _ = _read(script_path, script_encoding)
        verified_include, _ = _read(include_path, include_encoding)
        verified_count = len(_include_entries(verified_include, include_relative))
        if verified_script != rendered and script_status != "already_present":
            raise ValueError("script verification failed after write")
        if verified_count != 1:
            raise ValueError(f"include verification expected one entry, found {verified_count}")
    except Exception as exc:
        if created_script and script_path.exists():
            script_path.unlink()
        return {**result, "success": False, "error": str(exc), "rolled_back": created_script}

    return {**result, "verified": True}
